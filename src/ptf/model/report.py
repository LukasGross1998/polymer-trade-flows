"""Write `docs/model_results.md`: regional prices and rents, fit vs. observed trade, charts."""

from pathlib import Path

import pandas as pd

from ptf.core.markdown import to_markdown
from ptf.model.compare import plot_heatmaps
from ptf.model.transport import TransportResult


def region_table(result: TransportResult) -> pd.DataFrame:
    """Per region: capacity, model supply, demand, prices and rents in readable units."""
    regions = result.regions
    return pd.DataFrame(
        {
            "region": regions["region"],
            "capacity_kt": regions["capacity_t"] / 1000,
            "model_supply_kt": regions["supply_t"] / 1000,
            "utilisation_pct": regions["utilisation"] * 100,
            "demand_kt": regions["demand_t"] / 1000,
            "unmet_kt": regions["unmet_t"] / 1000,
            "prod_cost_usd_t": regions["prod_cost_usd_t"],
            "price_usd_t": regions["price_usd_t"],
            "rent_usd_t": regions["rent_usd_t"],
        }
    )


def build_model_report(
    result: TransportResult,
    table: pd.DataFrame,
    metrics: dict[str, float],
    regions: list[str],
    year: int,
    docs_dir: Path,
) -> Path:
    figures = docs_dir / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    plot_heatmaps(table, regions, figures / "model_vs_observed.png")

    routes = (
        f"{metrics['routes_used_observed']} / {metrics['routes_used_model']} / "
        f"{metrics['routes_used_both']}"
    )
    metric_rows = pd.DataFrame(
        [
            (
                "observed inter-regional trade (kt)",
                f"{metrics['observed_interregional_t'] / 1000:,.0f}",
            ),
            ("model inter-regional trade (kt)", f"{metrics['model_interregional_t'] / 1000:,.0f}"),
            ("explained share (%)", f"{metrics['explained_share'] * 100:.1f}"),
            ("routes used: observed / model / both", routes),
            ("correlation model vs. observed", f"{metrics['correlation']:.2f}"),
        ],
        columns=["metric", "value"],
    )

    top = table.head(15).assign(
        observed_kt=lambda d: d["observed_t"] / 1000, model_kt=lambda d: d["model_t"] / 1000
    )[["origin_region", "dest_region", "observed_kt", "model_kt"]]
    model_routes = (
        table[table["model_t"] > 1]
        .sort_values("model_t", ascending=False)
        .assign(
            model_kt=lambda d: d["model_t"] / 1000, observed_kt=lambda d: d["observed_t"] / 1000
        )
    )[["origin_region", "dest_region", "model_kt", "observed_kt"]]

    sections = [
        f"# Transport model results {year} (generated)",
        "Generated by `uv run ptf model`. Do not edit by hand. "
        "Assumptions: `config/model.yaml`; method and limits: "
        "[methodology.md](methodology.md#3-transport-model).",
        f"Total cost: **{result.total_cost_usd / 1e9:,.1f} bn USD**, "
        f"solver status: {result.status}.",
        "## 1. Regions: implied prices and scarcity rents",
        "`price_usd_t` = dual of the demand constraint "
        "(marginal delivered cost of one more tonne). "
        "`rent_usd_t` = dual of the capacity constraint (cost saving from one more tonne of "
        "capacity; 0 for regions with idle capacity).",
        to_markdown(region_table(result), decimals=0),
        "## 2. Model vs. observed inter-regional trade",
        "![model vs observed](figures/model_vs_observed.png)",
        to_markdown(metric_rows),
        "### Largest observed routes",
        to_markdown(top, decimals=0),
        "### Routes the model uses",
        to_markdown(model_routes, decimals=0),
    ]
    path = docs_dir / "model_results.md"
    path.write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    return path
